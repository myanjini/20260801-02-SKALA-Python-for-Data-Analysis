# 1. 숫자 연산
a = 10
b = 3

print("덧셈:", a + b)
print("나눗셈:", a / b)
print("몫:", a // b)
print("나머지:", a % b)
print("제곱:", a ** b)

# 2. 문자열 인덱싱 및 슬라이싱
text = "데이터 분석 파이썬"

print("\n전체 문자열:", text)
print("첫 번째 글자:", text[0])    # '데'
print("앞에서 3글자:", text[:3])   # '데이터'
print("5번째 글자부터:", text[4:]) # '분석 파이썬'